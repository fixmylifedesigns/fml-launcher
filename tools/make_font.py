"""Bake Inter into anti-aliased glyph bitmaps for the GameCube renderer.

Run from the project root:  python tools/make_font.py
Writes source/font_data.c and source/font_data.h.
"""
import os
from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TTF = os.path.join(ROOT, "tools", "fonts", "Inter.ttf")

# (enum name, pixel size, weight) - sizes match design/mockup.html
FONTS = [
    ("FONT_11B", 11, 700),
    ("FONT_12", 12, 400),
    ("FONT_13M", 13, 500),
    ("FONT_13S", 13, 600),
    ("FONT_14S", 14, 600),
    ("FONT_14B", 14, 700),
    ("FONT_15S", 15, 600),
    ("FONT_16B", 16, 700),
    ("FONT_19B", 19, 700),
    ("FONT_20B", 20, 700),
    ("FONT_26B", 26, 700),
    ("FONT_9K", 9, 800),     # cover band
    ("FONT_13B", 13, 700),   # cover title
    ("FONT_62K", 62, 900),   # cover initials
]

# ASCII 32..126, then extra symbols reachable through control codes \x01..
EXTRA = ["›", "‹", "·"]  # \x01 = ›, \x02 = ‹, \x03 = ·
CHARS = [chr(c) for c in range(32, 127)] + EXTRA


def bake(size, weight):
    font = ImageFont.truetype(TTF, size)
    font.set_variation_by_axes([max(14, min(32, size)), weight])
    glyphs, bitmap = [], bytearray()
    for ch in CHARS:
        x0, y0, x1, y1 = font.getbbox(ch, anchor="ls")
        w, h = max(0, x1 - x0), max(0, y1 - y0)
        adv = round(font.getlength(ch) * 16)
        off = len(bitmap)
        if w and h:
            img = Image.new("L", (w, h), 0)
            ImageDraw.Draw(img).text((-x0, -y0), ch, font=font, fill=255, anchor="ls")
            bitmap += img.tobytes()
        glyphs.append((w, h, x0, y0, adv, off))
    cap = -font.getbbox("H", anchor="ls")[1]
    return glyphs, bitmap, cap


def main():
    c = ['// Generated by tools/make_font.py from Inter (SIL Open Font License). Do not edit.',
         '#include "font_data.h"', '']
    table = []
    for name, size, weight in FONTS:
        glyphs, bitmap, cap = bake(size, weight)
        lname = name.lower()
        c.append(f"static const u8 {lname}_bits[] = {{")
        for i in range(0, len(bitmap), 32):
            c.append("\t" + ",".join(str(b) for b in bitmap[i:i + 32]) + ",")
        c.append("};")
        c.append(f"static const Glyph {lname}_glyphs[] = {{")
        for g in glyphs:
            c.append("\t{%d, %d, %d, %d, %d, %d}," % g)
        c.append("};")
        c.append("")
        table.append(f"\t[{name}] = {{ {lname}_glyphs, {lname}_bits, {size}, {cap} }},")
    c.append("const Font fonts[FONT_COUNT] = {")
    c += table
    c.append("};")

    h = ['// Generated by tools/make_font.py. Do not edit.',
         '#ifndef FONT_DATA_H', '#define FONT_DATA_H', '', '#include <gctypes.h>', '',
         'typedef struct {',
         '\tu8 w, h;      // bitmap size',
         '\ts8 x, y;      // bitmap offset from the pen position on the baseline',
         '\tu16 adv;      // advance in 1/16 px',
         '\tu32 off;      // offset into the font\'s bitmap',
         '} Glyph;', '',
         'typedef struct {',
         '\tconst Glyph *glyphs; // ASCII 32..126, then \\x01 = ›, \\x02 = ‹, \\x03 = ·',
         '\tconst u8 *bits;',
         '\tu8 size;',
         '\tu8 cap;              // cap height in px',
         '} Font;', '',
         'enum {']
    h += [f"\t{name}," for name, _, _ in FONTS]
    h += ['\tFONT_COUNT', '};', '', 'extern const Font fonts[FONT_COUNT];', '', '#endif', '']

    with open(os.path.join(ROOT, "source", "font_data.c"), "w", encoding="utf-8") as f:
        f.write("\n".join(c) + "\n")
    with open(os.path.join(ROOT, "source", "font_data.h"), "w", encoding="utf-8") as f:
        f.write("\n".join(h))


if __name__ == "__main__":
    main()
