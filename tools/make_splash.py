"""Bake the boot splash image into the launcher.

  python tools/make_splash.py design/splash/splash_a.png

Resizes to 640x480, dithers to RGB565 (so dark gradients don't band) and writes
source/splash_data.c in the GameCube's 4x4 tile layout.
"""
import os
import struct
import sys

from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
W, H = 640, 480


def main(path):
    img = Image.open(path).convert("RGB").resize((W, H), Image.LANCZOS)
    px = [list(img.getpixel((x, y))) for y in range(H) for x in range(W)]

    # Floyd-Steinberg dither down to 5/6/5 bits
    out = [0] * (W * H)
    levels = (31, 63, 31)
    for y in range(H):
        for x in range(W):
            i = y * W + x
            q = []
            for c in range(3):
                v = min(255, max(0, px[i][c]))
                n = round(v * levels[c] / 255)
                q.append(n)
                err = v - n * 255 / levels[c]
                for dx, dy, f in ((1, 0, 7), (-1, 1, 3), (0, 1, 5), (1, 1, 1)):
                    nx, ny = x + dx, y + dy
                    if 0 <= nx < W and ny < H:
                        px[ny * W + nx][c] += err * f / 16
            out[i] = (q[0] << 11) | (q[1] << 5) | q[2]

    tiles = bytearray()
    for ty in range(0, H, 4):
        for tx in range(0, W, 4):
            for y in range(ty, ty + 4):
                for x in range(tx, tx + 4):
                    tiles += struct.pack(">H", out[y * W + x])

    lines = ["// Generated by tools/make_splash.py from " + os.path.basename(path) + ". Do not edit.",
             "#include <gctypes.h>", "",
             f"const int splash_w = {W}, splash_h = {H};",
             "const u8 splash_tiles[] __attribute__((aligned(32))) = {"]
    for j in range(0, len(tiles), 32):
        lines.append("\t" + ",".join(str(b) for b in tiles[j:j + 32]) + ",")
    lines.append("};")
    with open(os.path.join(ROOT, "source", "splash_data.c"), "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"wrote source/splash_data.c ({len(tiles)} bytes of texture)")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        print(__doc__)
        sys.exit(1)
    main(sys.argv[1])
